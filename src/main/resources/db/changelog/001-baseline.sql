-- Compatible baseline for fresh databases and the previous H2 demonstration schema.
CREATE TABLE IF NOT EXISTS control (
id INT PRIMARY KEY, region VARCHAR(200), config VARCHAR(2000),
next_start BIGINT DEFAULT 0, failures INT DEFAULT 0, open_until BIGINT DEFAULT 0,
probe_task VARCHAR(40), turn BIGINT DEFAULT 0);

CREATE TABLE IF NOT EXISTS runs (
id VARCHAR(40) PRIMARY KEY, pub_id VARCHAR(200) NOT NULL UNIQUE,
product VARCHAR(200), target VARCHAR(200), cursor_value VARCHAR(2000),
finished BOOLEAN DEFAULT FALSE, active BOOLEAN DEFAULT TRUE);

CREATE TABLE IF NOT EXISTS firms (firm VARCHAR(200) PRIMARY KEY, last_turn BIGINT DEFAULT 0);

CREATE TABLE IF NOT EXISTS tasks (
id VARCHAR(40) PRIMARY KEY, run_id VARCHAR(40) REFERENCES runs(id),
region VARCHAR(200), firm VARCHAR(200), engagement VARCHAR(200), required_revision BIGINT,
state VARCHAR(30), attempts INT DEFAULT 0, operation_id VARCHAR(100),
due_at BIGINT, token BIGINT DEFAULT 0, lease_until BIGINT DEFAULT 0,
error_code VARCHAR(100), UNIQUE(run_id, firm, engagement));

CREATE TABLE IF NOT EXISTS outbox (task_id VARCHAR(40) PRIMARY KEY REFERENCES tasks(id), published BOOLEAN DEFAULT FALSE);

CREATE TABLE IF NOT EXISTS messages (
id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
task_id VARCHAR(40) REFERENCES tasks(id), visible_at BIGINT, receipt VARCHAR(40));

CREATE TABLE IF NOT EXISTS metadata (
firm VARCHAR(200), engagement VARCHAR(200), revision BIGINT, applied_version VARCHAR(200),
PRIMARY KEY(firm, engagement));
